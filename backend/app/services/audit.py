"""Audit trail PDF for "send for signature" requests."""
import hashlib
from datetime import timezone
from pathlib import Path

import pymupdf as fitz


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def _fmt(dt) -> str:
    if dt is None:
        return "-"
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")


class _Writer:
    """Tiny flowing-text writer on top of PyMuPDF with automatic page breaks."""

    def __init__(self):
        self.doc = fitz.open()
        self.w, self.h = fitz.paper_size("a4")
        self.margin = 50
        self._new_page()

    def _new_page(self):
        self.page = self.doc.new_page(width=self.w, height=self.h)
        self.y = self.margin

    def text(self, s: str, size: float = 10, bold: bool = False, color=(0, 0, 0), gap: float = 4):
        font = "hebo" if bold else "helv"
        max_w = self.w - 2 * self.margin
        words, line = s.split(" "), ""
        lines = []
        for word in words:
            trial = f"{line} {word}".strip()
            if fitz.get_text_length(trial, fontname=font, fontsize=size) > max_w and line:
                lines.append(line)
                line = word
            else:
                line = trial
        lines.append(line)
        for ln in lines:
            if self.y + size > self.h - self.margin:
                self._new_page()
            self.page.insert_text((self.margin, self.y + size), ln, fontsize=size, fontname=font, color=color)
            self.y += size * 1.35
        self.y += gap

    def rule(self):
        self.page.draw_line((self.margin, self.y), (self.w - self.margin, self.y), color=(0.8, 0.8, 0.8), width=0.7)
        self.y += 8

    def save(self, path: Path):
        self.doc.save(path, garbage=3, deflate=True)


def build_audit_pdf(request, original_path: Path, final_path: Path | None, out: Path) -> Path:
    w = _Writer()
    w.text("Signature Audit Trail", size=20, bold=True, gap=10)
    w.text(f"Document: {request.title}", size=11, bold=True)
    w.text(f"Request ID: {request.id}")
    w.text(f"Status: {request.status.upper()}")
    w.text(f"Created: {_fmt(request.created_at)}")
    w.text(f"Completed: {_fmt(request.completed_at)}")
    w.text(f"Original document SHA-256: {sha256_file(original_path)}", size=8)
    if final_path is not None:
        w.text(f"Final document SHA-256: {sha256_file(final_path)}", size=8)
    w.rule()
    w.text("Signers", size=14, bold=True)
    for s in request.signers:
        w.text(f"{s.order}. {s.name} <{s.email}> - {s.status}" + (f" at {_fmt(s.signed_at)}" if s.signed_at else ""))
    w.rule()
    w.text("Event history", size=14, bold=True)
    for e in request.events:
        w.text(f"{_fmt(e.created_at)}  {e.action.upper()}  by {e.actor}", bold=True, gap=1)
        details = e.detail or ""
        if e.ip:
            details += f"  IP: {e.ip}"
        if e.user_agent:
            details += f"  Browser: {e.user_agent[:120]}"
        if details.strip():
            w.text(details.strip(), size=8, color=(0.3, 0.3, 0.3))
    w.rule()
    w.text(
        "This audit trail was generated by PDFDesk. Hashes allow anyone to verify that the signed document "
        "has not been altered after signing.",
        size=8,
        color=(0.4, 0.4, 0.4),
    )
    w.save(out)
    return out
